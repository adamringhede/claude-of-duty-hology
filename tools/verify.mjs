import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.PORT_URL ?? 'http://127.0.0.1:5188';
const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--enable-unsafe-webgpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], checks = [];
const check = (name, condition, detail) => { assert.ok(condition, `${name}: ${JSON.stringify(detail)}`); checks.push({name,detail}); console.log('PASS',name,JSON.stringify(detail)); };
page.on('pageerror', e => {errors.push(e.stack); console.error(e.stack);});
page.on('console', msg => { if(msg.type()==='error') {errors.push(msg.text());console.error(msg.text());} else if (msg.text().includes('[port]') || msg.text().includes('static draw') || msg.text().includes('Keeping static root') || msg.text().includes('[Hology GPU VFX warmup]')) console.log(msg.text()); });
await page.addInitScript(() => {
 window.__CONTEXT_REQUESTS__=[];
 const original=HTMLCanvasElement.prototype.getContext;
 HTMLCanvasElement.prototype.getContext=function(type,...args) { window.__CONTEXT_REQUESTS__.push(type); return original.call(this,type,...args); };
});
const state = () => page.evaluate(() => {
 const e=window.__ENGINE__, p=e.ctx.get('player'), w=e.ctx.get('weapons');
 return {frame:e.time.frame,position:p.position.toArray(),stance:p.stance,health:p.getHudState().health,ads:w.adsProgress,ammo:w.getHudState().ammo,rounds:w.ammo.mag,weapon:w.activeId,reloading:w.reloading};
});
const frames = async n => {
 const start=(await state()).frame;
 await page.waitForFunction(start=>window.__ENGINE__.time.frame>=start,start+n,{timeout:90000});
};
try {
 await fs.mkdir(new URL('../artifacts/',import.meta.url),{recursive:true});
 await page.goto(base);
 await page.waitForFunction(()=>window.__READY__,null,{timeout:180000});
 await frames(90);
 check('Hology WebGPU backend',await page.evaluate(()=>window.__HOLOGY_VIEW__.activeBackend==='webgpu'));
 check('Static level draw set active',await page.evaluate(()=>[...window.__HOLOGY_VIEW__.view.experimentalStaticDrawSetRegistrations].some(r=>r.staticDrawSet?.drawCount>0)));
 const contexts=await page.evaluate(()=>window.__CONTEXT_REQUESTS__);
 check('No WebGL context requested',!contexts.some(type=>type.includes('webgl')), [...new Set(contexts)]);
 const ai=await page.evaluate(()=>window.__ENGINE__.ctx.get('ai').stats);
 check('AI garrison and navigation',ai.agents>=6&&ai.walkable>1000,ai);
 const before=await state();
 await page.keyboard.down('w'); await frames(24); await page.keyboard.up('w'); await frames(2);
 const moved=await state();
 const distance=Math.hypot(moved.position[0]-before.position[0],moved.position[2]-before.position[2]);
 check('Keyboard movement and collision simulation',distance>0.3&&Number.isFinite(moved.position[1]),{distance});
 await page.keyboard.down('Control'); await frames(15);
 check('Crouch', (await state()).stance==='crouch');
 await page.keyboard.up('Control'); await frames(12);
 const initialAmmo=(await state()).rounds;
 await page.mouse.click(650,440);
 await frames(2);
 check('Pointer lock', await page.evaluate(()=>window.__ENGINE__.input.pointerLocked));
 await page.mouse.down(); await frames(3); await page.mouse.up(); await frames(2);
 const fired=await state();
 check('Firing consumes ammunition',fired.rounds<initialAmmo,{before:initialAmmo,after:fired.rounds});
 await page.screenshot({path:new URL('../artifacts/firing.png',import.meta.url).pathname.replace(/^\/(.:)/,'$1')});
 await page.mouse.down({button:'right'}); await frames(20);
 check('Aim down sights',(await state()).ads>0.7,(await state()).ads);
 await page.screenshot({path:new URL('../artifacts/ads.png',import.meta.url).pathname.replace(/^\/(.:)/,'$1')});
 await page.mouse.up({button:'right'}); await frames(12);
 await page.evaluate(()=>{ window.__PLAYER_RELOAD__=[]; window.__ENGINE__.events.on('weapon:reload',e=>{ if(e.weapon===window.__ENGINE__.ctx.get('weapons').current) window.__PLAYER_RELOAD__.push(e.phase); }); });
 await page.keyboard.press('r');
 await page.waitForFunction(()=>window.__PLAYER_RELOAD__.includes('start'),null,{timeout:90000});
 check('Reload begins',await page.evaluate(()=>window.__PLAYER_RELOAD__.includes('start')));
 await page.waitForFunction(()=>{const w=window.__ENGINE__.ctx.get('weapons');return !w.reloading&&w.getHudState().ammo===30;},null,{timeout:90000});
 check('Reload refills magazine',(await state()).ammo===30);
 await page.keyboard.press('2');
 await page.waitForFunction(()=>window.__ENGINE__.ctx.get('weapons').activeId==='smg'&&!window.__ENGINE__.ctx.get('weapons').switching,null,{timeout:90000});
 check('Weapon switch',(await state()).weapon==='smg');
 await page.keyboard.press('1'); await frames(45);
 await page.evaluate(()=>{
  const e=window.__ENGINE__, ai=e.ctx.get('ai');
  window.__EXPLOSIONS__=0; e.events.on('explosion',()=>window.__EXPLOSIONS__++);
  const from=e.camera.position.clone().addScaledVector(e.ctx.get('player').forward,25);
  ai.throwGrenade(ai.agents[0],from,from.clone().addScaledVector(e.ctx.get('player').forward,10));
 });
 await page.waitForFunction(()=>window.__EXPLOSIONS__>0,null,{timeout:90000});
 check('AI grenade physics and explosion event',await page.evaluate(()=>window.__EXPLOSIONS__>0));
 await page.keyboard.press('Escape'); await frames(3);
 check('Pause menu and simulation pause',await page.evaluate(()=>window.__ENGINE__.ctx.get('ui').menu.open&&window.__ENGINE__.time.scale===0));
 await page.getByRole('button',{name:'low',exact:true}).click();
 check('Graphics preset updates Hology render scale',await page.evaluate(()=>Math.abs(window.__HOLOGY_VIEW__.view.currentResolutionScale-0.72)<0.01));
 await page.getByRole('button',{name:'high',exact:true}).click();
 await page.getByRole('button',{name:'Resume',exact:true}).click(); await frames(3);
 check('Resume',await page.evaluate(()=>window.__ENGINE__.time.scale===1));
 await page.setViewportSize({width:1280,height:720}); await frames(3);
 check('Viewport resize',await page.evaluate(()=>Math.abs(window.__ENGINE__.camera.aspect-1280/720)<0.01));
 await page.screenshot({path:new URL('../artifacts/port-game.png',import.meta.url).pathname.replace(/^\/(.:)/,'$1')});
 check('No browser or GPU validation errors',errors.length===0,errors);
 const profile=await page.evaluate(()=>window.__HOLOGY_VIEW__.getLastFrameProfile());
 await fs.writeFile(new URL('../artifacts/verification.json',import.meta.url),JSON.stringify({url:base,checks,errors,profile},null,2));
 console.log('VERIFIED',checks.length,'checks');
} finally {await browser.close();}
